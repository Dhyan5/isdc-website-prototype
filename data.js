// --- Animation helpers (pure DOM side effects, no React re-render needed) ---
export function setupReveal(rootEl) {
  if (!rootEl || typeof IntersectionObserver === 'undefined') return null;
  const els = rootEl.querySelectorAll('[data-reveal]');
  const pending = new Set(els);
  const reveal = (el) => {
    if (!pending.has(el)) return;
    pending.delete(el);
    const idx = Number(el.dataset.revealIdx || 0);
    el.style.transitionDelay = Math.min(idx, 8) * 70 + 'ms';
    el.style.opacity = '1';
    el.style.transform = 'translate(0,0)';
  };
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) { reveal(entry.target); io.unobserve(entry.target); }
    });
  }, { threshold: 0.01, rootMargin: '150px 0px -20px 0px' });
  els.forEach((el) => io.observe(el));
  // Safety net: catch anything the observer misses (fast/programmatic scroll jumps).
  const sweep = () => {
    if (!pending.size) { clearInterval(timer); return; }
    const vh = window.innerHeight || 800;
    pending.forEach((el) => {
      const r = el.getBoundingClientRect();
      if (r.top < vh * 1.4 && r.bottom > -vh * 0.4) { reveal(el); io.unobserve(el); }
    });
  };
  const timer = setInterval(sweep, 400);
  return io;
}

export function setupCounters(rootEl) {
  if (!rootEl || typeof IntersectionObserver === 'undefined') return null;
  const els = rootEl.querySelectorAll('[data-count]');
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        const el = entry.target;
        const target = Number(el.dataset.count || 0);
        const start = performance.now();
        const dur = 1300;
        function tick(now) {
          const t = Math.min(1, (now - start) / dur);
          const ease = 1 - Math.pow(1 - t, 3);
          el.textContent = Math.round(target * ease) + '+';
          if (t < 1) requestAnimationFrame(tick);
        }
        requestAnimationFrame(tick);
        io.unobserve(el);
      }
    });
  }, { threshold: 0.4 });
  els.forEach((el) => io.observe(el));
  return io;
}
